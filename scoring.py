"""Heuristic AI-likelihood index and reader-facing labels."""
import math
import config

HUMAN_LABEL = "This writing appears likely to have been written by a person. This assessment can be wrong."
AI_LABEL = "This writing appears likely to have been generated by AI. This assessment can be wrong; the writer can request a review."
UNSURE_LABEL = "We cannot reliably tell how this writing was created. This is not an accusation; the writer can request a review."

def _score(value):
    value = float(value)
    if not math.isfinite(value) or not 0 <= value <= 1:
        raise ValueError("Scores must be finite numbers between 0 and 1.")
    return value

def combine_signals(model_score: float, style_score: float) -> float:
    """Weight model 70%, style 30%; large disagreement forces uncertainty."""
    model_score, style_score = _score(model_score), _score(style_score)
    result = config.WEIGHT_MODEL_SIGNAL * model_score + config.WEIGHT_STYLE_SIGNAL * style_score
    if abs(model_score - style_score) >= config.DISAGREEMENT_THRESHOLD:
        result = min(0.65, max(0.35, result))
    return round(_score(result), 4)

def score_to_label(score: float) -> tuple[str, str]:
    score = _score(score)
    if score >= config.AI_THRESHOLD:
        return "ai", AI_LABEL
    if score <= config.HUMAN_THRESHOLD:
        return "human", HUMAN_LABEL
    return "unsure", UNSURE_LABEL

def label_ranges() -> list[tuple[str, str]]:
    return [
        ("high-confidence human", f"0 <= score <= {config.HUMAN_THRESHOLD:.2f}"),
        ("unsure", f"{config.HUMAN_THRESHOLD:.2f} < score < {config.AI_THRESHOLD:.2f}"),
        ("high-confidence AI", f"{config.AI_THRESHOLD:.2f} <= score <= 1"),
    ]

if __name__ == "__main__":
    for name, interval in label_ranges():
        print(f"{name}: {interval}")
